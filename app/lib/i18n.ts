/** Exported for scripts/verify-i18n.ts's own key-parity check -- not otherwise consumed outside this module. */
export const I18N: Record<LangCode, Dict> = { en, ja, es, fr, ko, zh, ru };

export function t(key: string, lang: LangCode, vars?: Record<string, string | number>): string {
  let s = I18N[lang]?.[key] ?? I18N.en[key] ?? key; // fallback chain: lang -> en -> raw key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
